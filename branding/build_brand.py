#!/usr/bin/env python3
"""Builds every Rallyto brand file from one source: the rally-loop geometry in mark.json.

    python branding/build_brand.py            # writes the SVG files in branding/
    python branding/build_brand.py --render   # also rasterises the icons and splash images of every app

The mark: two tapered arcs close a loop, each the path of a ball from one player to the other, and each ends in the
ball that reaches the partner (white trail -> yellow ball, yellow trail -> white ball). The second arc and ball are
the first turned 180 degrees about the centre. Read branding/README.md for what goes where.

Rendering uses headless Chrome (--chrome, $CHROME, or the default install path), so the PNGs follow the SVGs
exactly; Pillow only resamples and writes PNG/ICO. Re-run after changing mark.json; the Flutter BrandMark painter
and the landing's BrandMark component read the same numbers (brand_mark_test.dart pins the Flutter copy).
"""
from __future__ import annotations

import argparse
import json
import math
import os
import shutil
import subprocess
import tempfile
from pathlib import Path

BRANDING = Path(__file__).resolve().parent
ROOT = BRANDING.parent
SPEC = json.loads((BRANDING / "mark.json").read_text(encoding="utf-8"))
COLORS = SPEC["colors"]


def app_dir() -> Path:
    """The Flutter project: the one `*-app` folder with a pubspec (rallyto-app)."""
    for pubspec in sorted(ROOT.glob("*-app/pubspec.yaml")):
        return pubspec.parent
    raise SystemExit("Flutter app folder not found")


# ---------------------------------------------------------------------------------------------------------------
# Geometry
# ---------------------------------------------------------------------------------------------------------------

def _pt(radius: float, degrees: float) -> tuple[float, float]:
    cx, cy = SPEC["center"]
    a = math.radians(degrees)
    return cx + radius * math.cos(a), cy + radius * math.sin(a)


def _f(n: float) -> str:
    return f"{n:.2f}".rstrip("0").rstrip(".")


def trail_path(rotation: float) -> str:
    """The tapered arc: a point at its tail, widening (width * t^taper) to a round head where the ball sits."""
    r = SPEC["ringRadius"]
    t_spec = SPEC["trail"]
    a, b, w, e, n = t_spec["fromDeg"] + rotation, t_spec["toDeg"] + rotation, t_spec["width"], t_spec["taper"], t_spec["samples"]
    outer, inner = [], []
    for k in range(n + 1):
        t = k / n
        angle = a + (b - a) * t
        half = (w / 2) * t ** e
        outer.append(_pt(r + half, angle))
        inner.append(_pt(r - half, angle))
    head = w / 2
    d = "M" + " L".join(f"{_f(x)} {_f(y)}" for x, y in outer)
    d += f" A{_f(head)} {_f(head)} 0 0 1 {_f(inner[-1][0])} {_f(inner[-1][1])}"
    d += " L" + " L".join(f"{_f(x)} {_f(y)}" for x, y in reversed(inner)) + "Z"
    return d


def ball_circle(rotation: float, fill: str) -> str:
    x, y = _pt(SPEC["ringRadius"], SPEC["ball"]["angleDeg"] + rotation)
    return f'<circle cx="{_f(x)}" cy="{_f(y)}" r="{_f(SPEC["ball"]["radius"])}" fill="{fill}"/>'


def mark(trail_a: str, ball_a: str, trail_b: str, ball_b: str) -> str:
    return (
        f'<path d="{trail_path(0)}" fill="{trail_a}"/>'
        f'<path d="{trail_path(180)}" fill="{trail_b}"/>'
        f"{ball_circle(0, ball_a)}{ball_circle(180, ball_b)}"
    )


REVERSED = mark(COLORS["white"], COLORS["ball"], COLORS["ball"], COLORS["white"])
COLOR = mark(COLORS["green"], COLORS["clay"], COLORS["clay"], COLORS["green"])
MONO = mark(COLORS["ink"], COLORS["ink"], COLORS["ink"], COLORS["ink"])

TILE = SPEC["tile"]
GRADIENT = (
    '<defs><linearGradient id="rallyto-tile" x1="0" y1="0" x2="1" y2="1">'
    f'<stop offset="0" stop-color="{TILE["gradientFrom"]}"/><stop offset="1" stop-color="{TILE["gradientTo"]}"/>'
    "</linearGradient></defs>"
)


def svg(body: str, comment: str, view: str = "0 0 100 100", size: str = 'width="100" height="100"') -> str:
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" {size} viewBox="{view}" fill="none">\n'
        f"  <!-- Rallyto (رالیتو): {comment} Generated by branding/build_brand.py from mark.json; do not edit. -->\n"
        f"  {body}\n</svg>\n"
    )


# The mark is drawn at 90% inside the tile, so the balls keep a margin from its edge.
TILE_MARK_SCALE = 0.9
TILE_WITH_MARK = (
    f"{GRADIENT}<rect width=\"100\" height=\"100\" rx=\"{TILE['cornerRadius']}\" fill=\"url(#rallyto-tile)\"/>"
    f'<g transform="translate(50 50) scale({TILE_MARK_SCALE}) translate(-50 -50)">{REVERSED}</g>'
)


def lockup_persian(width: int = 320) -> str:
    """Persian reads from the right: the tile leads on the right, the wordmark follows to its left."""
    body = (
        f'<g transform="translate({width - 100} 0)">{TILE_WITH_MARK}</g>'
        f'<text x="{width - 122}" y="70" direction="rtl" text-anchor="start" font-family="Vazir, Vazirmatn, sans-serif" '
        f'font-size="58" font-weight="700" fill="{COLORS["ink"]}">رالیتو</text>'
    )
    return svg(body, "the Persian lockup (reference only; the text needs the Vazir font).", f"0 0 {width} 100", f'width="{width}" height="100"')


def lockup_latin(width: int = 340) -> str:
    body = (
        f"{TILE_WITH_MARK}"
        f'<text x="122" y="70" font-family="Inter, Vazirmatn, sans-serif" font-size="56" font-weight="700" '
        f'fill="{COLORS["ink"]}">Rallyto</text>'
    )
    return svg(body, "the Latin lockup (reference only).", f"0 0 {width} 100", f'width="{width}" height="100"')


SVG_FILES = {
    "symbol-reversed.svg": svg(REVERSED, "the mark for dark or brand-green backgrounds (white and ball yellow)."),
    "symbol-color.svg": svg(COLOR, "the mark for light backgrounds (court green and clay)."),
    "symbol-mono.svg": svg(MONO, "the mark in one colour (print, silhouettes, themed icons)."),
    "appicon.svg": svg(TILE_WITH_MARK, "the app icon: the reversed mark on the rounded court-green tile."),
    "fullbleed.svg": svg(
        f"{GRADIENT}<rect width=\"100\" height=\"100\" fill=\"url(#rallyto-tile)\"/>"
        f'<g transform="translate(50 50) scale(0.78) translate(-50 -50)">{REVERSED}</g>',
        "an uncut square for platforms that apply their own mask (iOS, store listings, maskable web icons).",
    ),
    "lockup-persian.svg": lockup_persian(),
    "lockup-latin.svg": lockup_latin(),
}


def write_svgs() -> None:
    for name, content in SVG_FILES.items():
        (BRANDING / name).write_text(content, encoding="utf-8")
        print(f"  branding/{name}")


# ---------------------------------------------------------------------------------------------------------------
# Rasterising
# ---------------------------------------------------------------------------------------------------------------

CANVAS = 1024
# The mark's drawn diameter as a share of its 100-unit grid (ring 25 + ball 10.5, both sides).
MARK_EXTENT = 2 * (SPEC["ringRadius"] + SPEC["ball"]["radius"]) / SPEC["grid"]
# Android adaptive icons: 108 dp, of which the central 66 dp circle is always visible. The mark is drawn 60 dp wide.
ADAPTIVE_SCALE = (60 / 108) / MARK_EXTENT

COMPOSITIONS = {
    # name: (background CSS, SVG, scale of the SVG within the canvas)
    "appicon": ("transparent", "appicon.svg", 1.0),
    "fullbleed": ("transparent", "fullbleed.svg", 1.0),
    "adaptive-foreground": ("transparent", "symbol-reversed.svg", ADAPTIVE_SCALE),
    "adaptive-monochrome": ("transparent", "symbol-mono.svg", ADAPTIVE_SCALE),
    # Android 12+ splash icon without an icon background: 288 dp, the content inside the central 192 dp circle.
    # The tile is drawn 96 dp wide, the size the Flutter launch splash starts at, so the hand-off does not jump.
    "splash12": ("transparent", "appicon.svg", 1 / 3),
}

ANDROID_DENSITIES = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}


def find_chrome(explicit: str | None) -> str:
    candidates = [
        explicit,
        os.environ.get("CHROME"),
        r"C:\Program Files\Google\Chrome\Application\chrome.exe",
        r"C:\Program Files (x86)\Google\Chrome\Application\chrome.exe",
        "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
    ]
    candidates += [shutil.which(n) for n in ("google-chrome", "chromium", "chromium-browser", "chrome")]
    for c in candidates:
        if c and Path(c).exists():
            return c
    raise SystemExit("No Chrome found: pass --chrome or set $CHROME")


def render(chrome: str, background: str, svg_name: str, scale: float, workdir: Path):
    from PIL import Image

    size = round(CANVAS * scale)
    offset = (CANVAS - size) // 2
    page = workdir / "page.html"
    shot = workdir / "shot.png"
    page.write_text(
        f"<html><body style='margin:0;background:{background}'>"
        f"<img src='{(BRANDING / svg_name).as_uri()}' style='position:absolute;left:{offset}px;top:{offset}px;"
        f"width:{size}px;height:{size}px'></body></html>",
        encoding="utf-8",
    )
    subprocess.run(
        [chrome, "--headless=new", "--disable-gpu", "--no-sandbox", "--hide-scrollbars", "--allow-file-access-from-files",
         "--force-device-scale-factor=1", "--default-background-color=00000000", f"--window-size={CANVAS},{CANVAS}",
         f"--screenshot={shot}", page.as_uri()],
        check=True, capture_output=True,
    )
    return Image.open(shot).convert("RGBA").copy()


def save_png(image, px: int, dest: Path, opaque: bool = False, white: bool = False) -> None:
    from PIL import Image

    out = image.resize((px, px), Image.LANCZOS)
    if white:  # a silhouette: keep the shape (alpha), paint it white
        out = Image.merge("RGBA", (*Image.new("RGB", out.size, (255, 255, 255)).split(), out.getchannel("A")))
    if opaque:  # App Store and store-listing icons must not carry an alpha channel
        out = out.convert("RGB")
    dest.parent.mkdir(parents=True, exist_ok=True)
    out.save(dest, optimize=True)
    print(f"  {dest.relative_to(ROOT)} ({px}px)")


def save_ico(image, sizes: list[int], dest: Path) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    image.save(dest, format="ICO", sizes=[(s, s) for s in sizes])
    print(f"  {dest.relative_to(ROOT)} ({', '.join(map(str, sizes))})")


def flutter_app(img: dict) -> None:
    app = app_dir()
    res = app / "android/app/src/main/res"
    for density, factor in ANDROID_DENSITIES.items():
        save_png(img["appicon"], round(48 * factor), res / f"mipmap-{density}/ic_launcher.png")
        save_png(img["adaptive-foreground"], round(108 * factor), res / f"mipmap-{density}/ic_launcher_foreground.png")
        save_png(img["adaptive-monochrome"], round(108 * factor), res / f"mipmap-{density}/ic_launcher_monochrome.png", white=True)
        save_png(img["appicon"], round(96 * factor), res / f"drawable-{density}/launch_mark.png")
        save_png(img["splash12"], round(288 * factor), res / f"drawable-{density}/splash_icon.png")
        # The status-bar notification icon must be a white silhouette on transparency (24 dp).
        save_png(img["adaptive-monochrome"], round(24 * factor), res / f"drawable-{density}/ic_notification.png", white=True)

    ios = app / "ios/Runner/Assets.xcassets"
    for entry in json.loads((ios / "AppIcon.appiconset/Contents.json").read_text())["images"]:
        px = round(float(entry["size"].split("x")[0]) * int(entry["scale"].rstrip("x")))
        save_png(img["fullbleed"], px, ios / "AppIcon.appiconset" / entry["filename"], opaque=True)
    for scale, suffix in ((1, ""), (2, "@2x"), (3, "@3x")):
        save_png(img["appicon"], 96 * scale, ios / f"LaunchImage.imageset/LaunchImage{suffix}.png")


def web_icons(img: dict, public: Path, extra: bool) -> None:
    save_ico(img["appicon"], [16, 32, 48], public / "favicon.ico")
    shutil.copyfile(BRANDING / "appicon.svg", public / "favicon.svg")
    print(f"  {(public / 'favicon.svg').relative_to(ROOT)}")
    save_png(img["fullbleed"], 180, public / "apple-touch-icon.png", opaque=True)
    if extra:
        save_png(img["appicon"], 512, public / "brand/logo-512.png")
        save_png(img["appicon"], 192, public / "icons/icon-192.png")
        save_png(img["appicon"], 512, public / "icons/icon-512.png")
        save_png(img["fullbleed"], 512, public / "icons/maskable-512.png", opaque=True)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--render", action="store_true", help="also rasterise every app's icons and splash images")
    parser.add_argument("--chrome", help="path to a Chrome/Chromium binary")
    args = parser.parse_args()

    print("brand SVGs")
    write_svgs()
    if not args.render:
        return

    chrome = find_chrome(args.chrome)
    with tempfile.TemporaryDirectory() as tmp:
        img = {name: render(chrome, *spec, Path(tmp)) for name, spec in COMPOSITIONS.items()}

    print("player app")
    flutter_app(img)
    print("admin panel")
    web_icons(img, ROOT / "rallyto-admin/public", extra=False)
    # The sidebar and sign-in BrandMark component imports the icon as an asset.
    shutil.copyfile(BRANDING / "appicon.svg", ROOT / "rallyto-admin/src/assets/brand/appicon.svg")
    print("  rallyto-admin/src/assets/brand/appicon.svg")
    print("landing site")
    web_icons(img, ROOT / "rallyto-landing/public", extra=True)
    print("store listing icons")
    for px in (512, 1024):
        save_png(img["fullbleed"], px, BRANDING / f"store/rallyto-{px}.png", opaque=True)


if __name__ == "__main__":
    main()
